-- Azotrace: tickets de suporte com isolamento por empresa e acesso global Super Admin.
-- Aplicar depois de 20261002_azotrace_multitenant_rbac.sql.
begin;
create extension if not exists pgcrypto;

create table if not exists public.azotrace_support_tickets (
  id uuid primary key default gen_random_uuid(),
  ticket_number bigint generated by default as identity unique,
  company_id text not null references public.azotrace_companies(id) on delete restrict,
  subject text not null check (length(btrim(subject)) between 3 and 180),
  priority text not null default 'medium' check (priority in ('low','medium','high')),
  status text not null default 'open' check (status in ('open','waiting','resolved')),
  requester_name text not null check (length(btrim(requester_name)) > 0),
  requester_email text,
  created_by_user_id uuid not null references auth.users(id) on delete restrict,
  assignee_user_id uuid references auth.users(id) on delete set null,
  resolved_by_user_id uuid references auth.users(id) on delete set null,
  resolved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.azotrace_support_ticket_messages (
  id uuid primary key default gen_random_uuid(),
  ticket_id uuid not null references public.azotrace_support_tickets(id) on delete cascade,
  author_user_id uuid not null references auth.users(id) on delete restrict,
  author_name text not null,
  body text not null check (length(btrim(body)) > 0),
  is_internal boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists az_support_tickets_company_updated_idx
  on public.azotrace_support_tickets(company_id, updated_at desc);
create index if not exists az_support_tickets_status_updated_idx
  on public.azotrace_support_tickets(status, updated_at desc);
create index if not exists az_support_ticket_messages_ticket_created_idx
  on public.azotrace_support_ticket_messages(ticket_id, created_at);

drop trigger if exists az_support_ticket_updated_at on public.azotrace_support_tickets;
create trigger az_support_ticket_updated_at
  before update on public.azotrace_support_tickets
  for each row execute function public.azotrace_touch_updated_at();

alter table public.azotrace_support_tickets enable row level security;
alter table public.azotrace_support_ticket_messages enable row level security;

drop policy if exists az_support_tickets_select on public.azotrace_support_tickets;
create policy az_support_tickets_select on public.azotrace_support_tickets
  for select to authenticated
  using (public.azotrace_is_superadmin() or public.azotrace_can_access_company(company_id));

drop policy if exists az_support_tickets_insert on public.azotrace_support_tickets;
create policy az_support_tickets_insert on public.azotrace_support_tickets
  for insert to authenticated
  with check (
    created_by_user_id = auth.uid()
    and public.azotrace_can_access_company(company_id)
    and status = 'open'
    and assignee_user_id is null
    and resolved_by_user_id is null
  );

drop policy if exists az_support_tickets_update on public.azotrace_support_tickets;
create policy az_support_tickets_update on public.azotrace_support_tickets
  for update to authenticated
  using (public.azotrace_is_superadmin())
  with check (public.azotrace_is_superadmin());

drop policy if exists az_support_messages_select on public.azotrace_support_ticket_messages;
create policy az_support_messages_select on public.azotrace_support_ticket_messages
  for select to authenticated
  using (
    exists (
      select 1 from public.azotrace_support_tickets t
      where t.id = ticket_id
        and (public.azotrace_is_superadmin() or public.azotrace_can_access_company(t.company_id))
    )
    and (not is_internal or public.azotrace_is_superadmin())
  );

drop policy if exists az_support_messages_insert on public.azotrace_support_ticket_messages;
create policy az_support_messages_insert on public.azotrace_support_ticket_messages
  for insert to authenticated
  with check (
    author_user_id = auth.uid()
    and exists (
      select 1 from public.azotrace_support_tickets t
      where t.id = ticket_id
        and (public.azotrace_is_superadmin() or public.azotrace_can_access_company(t.company_id))
    )
    and (not is_internal or public.azotrace_is_superadmin())
  );

grant select, insert, update on public.azotrace_support_tickets to authenticated;
grant select, insert on public.azotrace_support_ticket_messages to authenticated;
grant usage, select on sequence public.azotrace_support_tickets_ticket_number_seq to authenticated;

create or replace function public.azotrace_support_create_ticket(
  input_company_id text,
  input_subject text,
  input_priority text,
  input_requester_name text,
  input_requester_email text,
  input_body text
)
returns uuid
language plpgsql
security invoker
set search_path = ''
as $$
declare
  new_ticket_id uuid;
  actor_name text;
begin
  if auth.uid() is null then
    raise exception 'É necessário iniciar sessão.' using errcode = '42501';
  end if;
  if not public.azotrace_can_access_company(input_company_id) then
    raise exception 'Sem acesso a esta empresa.' using errcode = '42501';
  end if;
  if input_priority not in ('low','medium','high') then
    raise exception 'Prioridade inválida.' using errcode = '22023';
  end if;
  select coalesce(nullif(btrim(p.name), ''), p.email, 'Utilizador') into actor_name
  from public.profiles p where p.id = auth.uid() and p.active is true;
  if actor_name is null then
    raise exception 'Perfil inativo ou inexistente.' using errcode = '42501';
  end if;

  insert into public.azotrace_support_tickets (
    company_id, subject, priority, requester_name, requester_email, created_by_user_id
  ) values (
    input_company_id, btrim(input_subject), input_priority,
    btrim(input_requester_name), nullif(btrim(input_requester_email), ''), auth.uid()
  ) returning id into new_ticket_id;

  insert into public.azotrace_support_ticket_messages (
    ticket_id, author_user_id, author_name, body, is_internal
  ) values (
    new_ticket_id, auth.uid(), actor_name, btrim(input_body), false
  );

  return new_ticket_id;
end;
$$;

revoke all on function public.azotrace_support_create_ticket(text,text,text,text,text,text) from public, anon;
grant execute on function public.azotrace_support_create_ticket(text,text,text,text,text,text) to authenticated;

create or replace function public.azotrace_support_touch_ticket_from_message()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.azotrace_support_tickets set updated_at = now() where id = new.ticket_id;
  return new;
end;
$$;

revoke all on function public.azotrace_support_touch_ticket_from_message() from public, anon, authenticated;
drop trigger if exists az_support_message_touch_ticket on public.azotrace_support_ticket_messages;
create trigger az_support_message_touch_ticket
  after insert on public.azotrace_support_ticket_messages
  for each row execute function public.azotrace_support_touch_ticket_from_message();

-- Realtime atualiza a lista e a conversa quando outro membro da equipa responde.
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'azotrace_support_tickets') then
      execute 'alter publication supabase_realtime add table public.azotrace_support_tickets';
    end if;
    if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'azotrace_support_ticket_messages') then
      execute 'alter publication supabase_realtime add table public.azotrace_support_ticket_messages';
    end if;
  end if;
end $$;

commit;
