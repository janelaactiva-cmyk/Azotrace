-- Aplicar depois das duas migrações de políticas de privacidade incluídas.
begin;
create table if not exists public.azotrace_rgpd_records(
 scope_key text not null,company_id text references public.azotrace_companies(id) on delete cascade,
 id uuid not null,kind text not null check(kind in ('consents','requests','retention','processors','activities','exports')),
 data jsonb not null check(jsonb_typeof(data)='object' and octet_length(data::text)<=100000),
 version integer not null check(version>0),created_at timestamptz not null default now(),updated_at timestamptz not null default now(),
 updated_by uuid references auth.users(id) on delete set null,
 search_text text generated always as(lower(data::text)) stored,
 primary key(scope_key,id),
 check((scope_key='platform:azotrace' and company_id is null) or (company_id is not null and scope_key='company:'||company_id))
);
create index if not exists az_rgpd_records_scope_kind_updated on public.azotrace_rgpd_records(scope_key,kind,updated_at desc,id);
create table if not exists public.azotrace_rgpd_audit(
 id bigint generated by default as identity primary key,scope_key text not null,
 company_id text references public.azotrace_companies(id) on delete cascade,kind text not null,record_id text not null,title text not null,
 action text not null,version bigint not null,actor_id uuid references auth.users(id) on delete set null,actor_name text not null,
 snapshot jsonb not null,created_at timestamptz not null default now(),
 check((scope_key='platform:azotrace' and company_id is null) or (company_id is not null and scope_key='company:'||company_id))
);
create index if not exists az_rgpd_audit_scope_created on public.azotrace_rgpd_audit(scope_key,created_at desc,id desc);
alter table public.azotrace_rgpd_records enable row level security;
alter table public.azotrace_rgpd_audit enable row level security;
revoke all on public.azotrace_rgpd_records,public.azotrace_rgpd_audit from public,anon,authenticated,service_role;
grant select,insert,update on public.azotrace_rgpd_records to service_role;
grant select,insert on public.azotrace_rgpd_audit to service_role;
grant usage,select on sequence public.azotrace_rgpd_audit_id_seq to service_role;

create or replace function public.az_rgpd_save(p_scope text,p_company text,p_kind text,p_id uuid,p_data jsonb,p_version integer,p_actor uuid,p_actor_name text,p_title text)
returns jsonb language plpgsql security invoker set search_path='' as $$
declare saved public.azotrace_rgpd_records;
begin
 if p_actor is null or p_actor_name is null or length(btrim(p_actor_name))=0 or p_title is null or length(p_title)>500 or p_version<0 then raise exception 'rgpd_invalid'; end if;
 if p_version=0 then
  insert into public.azotrace_rgpd_records(scope_key,company_id,id,kind,data,version,updated_by)
  values(p_scope,p_company,p_id,p_kind,p_data,1,p_actor) on conflict(scope_key,id) do nothing returning * into saved;
  if not found then
   select * into saved from public.azotrace_rgpd_records where scope_key=p_scope and id=p_id and kind=p_kind;
   if found and saved.version=1 and saved.data=p_data and saved.updated_by=p_actor then return to_jsonb(saved)-'search_text'-'updated_by'-'scope_key'-'company_id'; end if;
   raise exception 'rgpd_conflict';
  end if;
 else
  update public.azotrace_rgpd_records set data=p_data,version=version+1,updated_by=p_actor,updated_at=now()
  where scope_key=p_scope and id=p_id and kind=p_kind and version=p_version returning * into saved;
  if not found then raise exception 'rgpd_conflict'; end if;
 end if;
 insert into public.azotrace_rgpd_audit(scope_key,company_id,kind,record_id,title,action,version,actor_id,actor_name,snapshot)
 values(p_scope,p_company,p_kind,p_id::text,p_title,case when p_kind='exports' then 'export' when p_version=0 then 'create' else 'update' end,saved.version,p_actor,p_actor_name,p_data);
 return to_jsonb(saved)-'search_text'-'updated_by'-'scope_key'-'company_id';
end; $$;
revoke all on function public.az_rgpd_save(text,text,text,uuid,jsonb,integer,uuid,text,text) from public,anon,authenticated;
grant execute on function public.az_rgpd_save(text,text,text,uuid,jsonb,integer,uuid,text,text) to service_role;

-- O histórico das políticas regista as versões dentro da mesma transação da gravação.
create or replace function public.az_rgpd_audit_policy()
returns trigger language plpgsql security invoker set search_path='' as $$
declare scope_value text; company_value text; author text; operation text;
begin
 if tg_table_name='azotrace_platform_privacy' then scope_value:='platform:azotrace';company_value:=null;
 else scope_value:='company:'||new.company_id;company_value:=new.company_id;end if;
 select coalesce(nullif(p.name,''),p.email,'Utilizador') into author from public.profiles p where p.id=new.updated_by;
 operation:='save';
 if tg_op='INSERT' then if new.published_at is not null then operation:='publish';end if;
 elsif new.published_at is distinct from old.published_at then operation:='publish';end if;
 insert into public.azotrace_rgpd_audit(scope_key,company_id,kind,record_id,title,action,version,actor_id,actor_name,snapshot)
 values(scope_value,company_value,'policy',new.company_id,'Política de privacidade',operation,new.version,new.updated_by,coalesce(author,'Utilizador'),jsonb_build_object('draft_content',new.draft_content,'published_content',new.published_content,'published_at',new.published_at));
 return new;
end; $$;
revoke all on function public.az_rgpd_audit_policy() from public,anon,authenticated;
grant execute on function public.az_rgpd_audit_policy() to service_role;
do $$ begin
 if to_regclass('public.azotrace_company_privacy') is not null then
  drop trigger if exists az_rgpd_policy_history on public.azotrace_company_privacy;
  create trigger az_rgpd_policy_history after insert or update on public.azotrace_company_privacy for each row execute function public.az_rgpd_audit_policy();
 end if;
 if to_regclass('public.azotrace_platform_privacy') is not null then
  drop trigger if exists az_rgpd_policy_history on public.azotrace_platform_privacy;
  create trigger az_rgpd_policy_history after insert or update on public.azotrace_platform_privacy for each row execute function public.az_rgpd_audit_policy();
 end if;
end $$;
commit;
